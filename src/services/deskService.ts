let currentDesks = [...initialDesks];

export const deskService = {
  getDesks(): Desk[] {
    return [...currentDesks];
  },

  getDeskById(id: string): Desk | undefined {
    return currentDesks.find((d) => d.id === id);
  },

  releaseSeat(deskId: string): Desk {
    const index = currentDesks.findIndex((d) => d.id === deskId);
    if (index >= 0) {
      currentDesks[index] = {
        ...currentDesks[index],
        isOccupied: false,
        occupant: undefined,
      };
      return currentDesks[index];
    }
    throw new Error('Desk not found');
  },

  reassignSeat(
    deskId: string,
    occupantData: Omit<DeskOccupant, 'id'>
  ): Desk {
    const index = currentDesks.findIndex((d) => d.id === deskId);
    if (index >= 0) {
      currentDesks[index] = {
        ...currentDesks[index],
        isOccupied: true,
        occupant: {
          ...occupantData,
          id: `occ-${Date.now()}`,
        },
      };
      return currentDesks[index];
    }
    throw new Error('Desk not found');
  },
};
